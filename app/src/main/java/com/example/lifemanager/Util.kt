            .replace(Regex("\\s+"), " ").trim()

    private data class Alias(val kw: String, val ref: FoodRef)

    private val aliases: List<Alias> by lazy {
        val list = mutableListOf<Alias>()
        for (r in catalog) {
            val clean = norm(r.name.substringBefore("("))
            clean.split("/").map { it.trim() }.filter { it.length >= 2 }.forEach {
                list.add(Alias(it, r))
            }
            val full = norm(r.name.replace("(", " ").replace(")", " "))
            if (full != clean) list.add(Alias(full, r))
        }
        list.sortedByDescending { it.kw.length }
    }

    fun estimate(text: String): Pair<List<Food>, List<String>> {
        val now = System.currentTimeMillis()
        val found = mutableListOf<Food>()
        val missing = mutableListOf<String>()
        val t = norm(text)
        val parts = t.split(Regex("[،,\\n+]|\\sو\\s")).map { it.trim() }.filter { it.isNotEmpty() }
        val fallbackKeys = per100.keys.sortedByDescending { it.length }

        for (p in parts) {
            val num = Regex("[0-9]+(?:\\.[0-9]+)?").find(p)?.value?.toDoubleOrNull()
            val hasGram = p.contains("گرم") || p.contains("میلی")
            val match = aliases.firstOrNull { p.contains(it.kw) }?.ref

            if (match != null) {
                val g: Int
                val kcal: Int
                if (hasGram && num != null) {
                    g = num.toInt()
                    val baseG = if (match.unitGrams > 0) match.unitGrams else 100
                    kcal = Math.round(num * match.calories / baseG).toInt()
                } else {
                    val mult = num ?: 1.0
                    g = Math.round(mult * match.unitGrams).toInt()
                    kcal = Math.round(mult * match.calories).toInt()
                }
                found.add(Food(name = match.name, grams = g, kcal = kcal, date = now))
                continue
            }

            val key = fallbackKeys.firstOrNull { p.contains(it) }
            if (key == null) {
                missing.add(p)
                continue
            }
            val pw = piece[key]
            val grams: Double = when {
                num == null -> 100.0
                pw != null && (p.contains("عدد") || (num <= 10 && !hasGram)) -> num * pw
                else -> num
            }
            val kcal = (grams * (per100[key] ?: 0) / 100.0).toInt()
            found.add(Food(name = p, grams = grams.toInt(), kcal = kcal, date = now))
        }
        return Pair(found, missing)
    }
